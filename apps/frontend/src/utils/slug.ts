/**
 * Транслитерирует вьетнамские символы в латиницу (оптимизированная версия)
 * @param text - текст для транслитерации
 * @returns транслитерированный текст
 */
function transliterateVietnamese(text: string): string {
	// Используем один проход через строку вместо множественных replace
	return text
		.split('')
		.map((char) => vietnameseMap.get(char) || char)
		.join('');
}

// Кэш для сгенерированных slug (ключ: name-id, значение: slug)
const slugCache = new Map<string, string>();

/**
 * Генерирует SEO-дружественный slug из названия салона и ID
 * @param name - название салона
 * @param id - ID салона
 * @param address - адрес салона (не используется, оставлен для совместимости)
 * @returns сгенерированный slug
 */
export function generateSalonSlug(
	name: string,
	id: string,
	address?: string
): string {
	// Проверяем кэш
	const cacheKey = `${name}-${id}`;
	if (slugCache.has(cacheKey)) {
		return slugCache.get(cacheKey)!;
	}

	// Сначала транслитерируем вьетнамские символы
	const transliteratedName = transliterateVietnamese(name);

	// Очищаем название салона (оптимизированная цепочка replace)
	const cleanName = transliteratedName
		.toLowerCase()
		.trim()
		.replace(/[^\w\s-]/g, '') // Удаляем специальные символы
		.replace(/\s+/g, '-') // Заменяем пробелы на дефисы
		.replace(/-+/g, '-') // Удаляем множественные дефисы
		.replace(/^-|-$/g, ''); // Удаляем дефисы в начале и конце

	// Используем полный ID для уникальности
	// Собираем slug: название-id
	const slug = `${cleanName}-${id}`;

	// Сохраняем в кэш (ограничиваем размер кэша для предотвращения утечек памяти)
	if (slugCache.size > 1000) {
		// Удаляем первые 100 записей (FIFO)
		const firstKeys = Array.from(slugCache.keys()).slice(0, 100);
		firstKeys.forEach((key) => slugCache.delete(key));
	}
	slugCache.set(cacheKey, slug);

	return slug;
}

/**
 * Извлекает ID салона из slug
 * @param slug - slug салона
 * @returns ID салона или null если не удалось извлечь
 * 
 * Оптимизированная версия: использует регулярное выражение для быстрого поиска ID в конце slug
 * ID (cuid) обычно начинается с 'c' и имеет длину 20+ символов
 */
export function extractSalonIdFromSlug(slug: string): string | null {
	// Оптимизация: используем регулярное выражение для поиска ID в конце
	// Паттерн: ID начинается с 'c' и содержит 20+ букв/цифр в конце строки
	const idMatch = slug.match(/-c[a-z0-9]{19,}$/i);
	if (idMatch) {
		// Убираем дефис в начале
		return idMatch[0].substring(1);
	}
	
	// Fallback для старых форматов или если ID в начале
	// Проверяем, может быть это просто ID без названия
	if (/^c[a-z0-9]{19,}$/i.test(slug)) {
		return slug;
	}
	
	return null;
}

/**
 * Проверяет, является ли строка валидным slug салона
 * @param slug - строка для проверки
 * @returns true если slug валидный
 */
export function isValidSalonSlug(slug: string): boolean {
	return /^[a-z0-9-]+$/.test(slug) && slug.length > 0;
}
